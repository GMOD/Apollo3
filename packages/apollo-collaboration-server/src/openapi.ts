/**
 * Writes the OpenAPI document for the collaboration server's REST API to
 * `openapi.json` at the root of this package. The website builds its API
 * reference from that file.
 *
 * This doesn't start the server or connect to MongoDB. It builds the Nest
 * module graph in preview mode, which registers controllers without
 * instantiating any providers.
 *
 * Run with `yarn workspace @apollo-annotation/collaboration-server run openapi`
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import * as apolloSchemas from '@apollo-annotation/schemas'
import { changes } from '@apollo-annotation/shared'
import { NestFactory } from '@nestjs/core'
import {
  DocumentBuilder,
  type OpenAPIObject,
  type OperationObject,
  type ReferenceObject,
  type SchemaObject,
  SwaggerModule,
} from '@nestjs/swagger'
import { Schema as MongooseSchema, type SchemaType } from 'mongoose'

import { Role } from './utils/role/role.enum.js'
import { getRequiredRoleForChange } from './utils/validation/validatation.changeTypePermissions.js'

const packageRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
)

// Placeholder values so the config validation in AppModule passes. Nothing
// uses them, since no providers are created in preview mode.
const placeholderEnv: Record<string, string> = {
  URL: 'http://localhost:3999',
  NAME: 'Apollo',
  MONGODB_URI: 'mongodb://localhost:27017/openapi',
  FILE_UPLOAD_FOLDER: '/tmp',
  JWT_SECRET: 'openapi',
  SESSION_SECRET: 'openapi',
}

// Environment variables that could change the output, or that conflict with
// the placeholders
const clearedEnv = [
  'PLUGIN_URLS',
  'PLUGIN_URLS_FILE',
  'MONGODB_URI_FILE',
  'JWT_SECRET_FILE',
  'SESSION_SECRET_FILE',
]

// Plain text, since the start of an operation's description is also shown
// where Markdown isn't rendered, such as on the website's tag pages
const roleDescriptions: Record<Role, string> = {
  [Role.None]: 'none',
  [Role.ReadOnly]: 'readOnly or higher',
  [Role.User]: 'user or higher',
  [Role.Admin]: 'admin',
}

// Controllers are tagged with their name, e.g. "Features" for
// FeaturesController. This sets the order the tags are listed in.
const tags: [name: string, description: string][] = [
  ['Authentication', 'Log in and get tokens'],
  ['Assemblies', 'Genome assemblies'],
  ['RefSeqs', "Assemblies' reference sequences"],
  ['Sequence', 'Sequence data'],
  ['Features', 'Annotation features'],
  ['Changes', 'Submit changes and read the change log'],
  ['Checks', 'Automated checks on features, such as for valid CDSs'],
  ['Files', 'Upload GFF3 and FASTA files to add with a change'],
  ['Export', "Download an assembly's annotations as GFF3"],
  ['Users', 'User accounts and locations'],
  ['JBrowse', 'JBrowse configuration'],
  ['Health', 'Server status and version'],
]

const httpMethods = [
  'get',
  'put',
  'post',
  'delete',
  'options',
  'head',
  'patch',
  'trace',
] as const

async function main() {
  for (const key of clearedEnv) {
    // eslint-disable-next-line @typescript-eslint/no-dynamic-delete
    delete process.env[key]
  }
  Object.assign(process.env, placeholderEnv)

  const packageJSON = JSON.parse(
    await fs.readFile(path.join(packageRoot, 'package.json'), 'utf8'),
  ) as { version: string; license: string }

  // Generated by scripts/generateOpenAPIMetadata.ts, which isn't checked in, so
  // the path isn't a literal to keep TypeScript from resolving it
  const metadataPath = './openapi-metadata.js'
  const { default: loadMetadata } = (await import(metadataPath)) as {
    default: () => Promise<Record<string, unknown>>
  }
  await SwaggerModule.loadPluginMetadata(loadMetadata)

  const { AppModule } = await import('./app.module.js')
  const app = await NestFactory.create(AppModule, {
    preview: true,
    logger: false,
    abortOnError: false,
  })

  const config = new DocumentBuilder()
    .setTitle('Apollo Collaboration Server')
    .setDescription(
      'The REST API of the Apollo collaboration server. Most endpoints need a token in an `Authorization: Bearer <token>` header.',
    )
    .setVersion(packageJSON.version)
    .setLicense(
      packageJSON.license,
      `https://spdx.org/licenses/${packageJSON.license}.html`,
    )
    .addServer('{baseUrl}', 'Your Apollo collaboration server', {
      baseUrl: {
        default: 'http://localhost:3999',
        description: "The server's URL, as set in its URL configuration",
      },
    })
    .addBearerAuth()
  for (const [name, description] of tags) {
    config.addTag(name, description)
  }
  const document = SwaggerModule.createDocument(app, config.build())
  await app.close()
  checkTags(document)

  for (const operation of getOperations(document)) {
    splitSummary(operation)
    addRoleInfo(operation)
  }
  addDatabaseSchemas(document)
  describeChangeBody(document)

  const outFile = path.join(packageRoot, 'openapi.json')
  await fs.writeFile(outFile, `${JSON.stringify(document, null, 2)}\n`)
  process.stdout.write(`Wrote ${path.relative(process.cwd(), outFile)}\n`)
}

/** Make sure every operation's tag is in the list of tags */
function checkTags(document: OpenAPIObject) {
  const tagNames = new Set(tags.map(([name]) => name))
  for (const operation of getOperations(document)) {
    for (const tag of operation.tags ?? []) {
      if (!tagNames.has(tag)) {
        throw new Error(`Tag "${tag}" is missing from the list of tags`)
      }
    }
  }
}

function* getOperations(document: OpenAPIObject) {
  for (const pathItem of Object.values(document.paths)) {
    for (const method of httpMethods) {
      const operation = pathItem[method]
      if (operation) {
        yield operation
      }
    }
  }
}

/**
 * The Swagger plugin puts a route's whole JSDoc comment in its summary. Keep
 * the first paragraph as the summary and move the rest to the description.
 */
function splitSummary(operation: OperationObject) {
  if (!operation.summary) {
    return
  }
  const [summary, ...rest] = operation.summary.split('\n\n')
  operation.summary = (summary ?? '').replaceAll('\n', ' ')
  const description = rest
    .map((paragraph: string) => paragraph.replaceAll('\n', ' '))
    .join('\n\n')
  if (description) {
    operation.description = operation.description
      ? `${description}\n\n${operation.description}`
      : description
  }
}

/**
 * Add the minimum role needed for an operation (set with the `Validations`
 * decorator) to its description, and make sure the operations that need a
 * token list it once in their security requirements
 */
function addRoleInfo(operation: OperationObject) {
  const operationWithRole = operation as OperationObject & {
    'x-apollo-role'?: Role
  }
  // Routes without a role need admin, see AuthorizationValidation
  const role = operationWithRole['x-apollo-role'] ?? Role.Admin
  operationWithRole['x-apollo-role'] = role
  const roleText = `Required role: ${roleDescriptions[role]}.`
  operation.description = operation.description
    ? `${roleText}\n\n${operation.description}`
    : roleText
  // A route that doesn't need a role can still use a token if it adds
  // ApiBearerAuth itself, e.g. to refresh the token
  operation.security =
    role !== Role.None || operation.security ? [{ bearer: [] }] : []
  if (role !== Role.None) {
    operation.responses['403'] ??= {
      description:
        "No token, or the token's user doesn't have the required role",
    }
  }
}

/**
 * Fill in the schemas of the database documents that endpoints return (e.g.
 * `Feature`) from their Mongoose schemas, since the Swagger plugin only sees
 * this package's classes
 */
function addDatabaseSchemas(document: OpenAPIObject) {
  const componentSchemas = (document.components ??= {}).schemas ?? {}
  document.components.schemas = componentSchemas
  const mongooseSchemas = new Map<string, MongooseSchema>()
  for (const [exportName, value] of Object.entries(apolloSchemas)) {
    if (value instanceof MongooseSchema && exportName.endsWith('Schema')) {
      mongooseSchemas.set(exportName.slice(0, -'Schema'.length), value)
    }
  }
  const schemaNames = new Map<MongooseSchema, string>()
  for (const [name, schema] of mongooseSchemas) {
    schemaNames.set(schema, name)
  }
  // Add the ones that are referenced, and any they reference in turn
  const queue = [...mongooseSchemas.keys()].filter((name) => {
    const existing = componentSchemas[name]
    return existing !== undefined || isReferenced(document, name)
  })
  const done = new Set<string>()
  while (queue.length > 0) {
    const name = queue.shift()
    if (name === undefined || done.has(name)) {
      continue
    }
    done.add(name)
    const schema = mongooseSchemas.get(name)
    if (!schema) {
      continue
    }
    const referenced: string[] = []
    componentSchemas[name] = mongooseToOpenAPI(schema, schemaNames, referenced)
    queue.push(...referenced)
  }
}

function isReferenced(document: OpenAPIObject, name: string) {
  return JSON.stringify(document.paths).includes(
    `"#/components/schemas/${name}"`,
  )
}

function mongooseToOpenAPI(
  schema: MongooseSchema,
  schemaNames: Map<MongooseSchema, string>,
  referenced: string[],
): SchemaObject {
  const root: SchemaObject & { properties: Record<string, SchemaObject> } = {
    type: 'object',
    properties: {},
  }
  const required: string[] = []
  schema.eachPath((pathName, schemaType) => {
    // "$*" paths are the values of a Map, which the Map path already covers
    if (pathName === '__v' || pathName.endsWith('.$*')) {
      return
    }
    // Nested paths like "a.b" become nested objects
    const parts = pathName.split('.')
    const propertyName = parts.pop() ?? pathName
    let parent = root
    for (const part of parts) {
      const child = (parent.properties[part] ??= {
        type: 'object',
        properties: {},
      }) as typeof root
      parent = child
    }
    parent.properties[propertyName] = schemaTypeToOpenAPI(
      schemaType,
      schemaNames,
      referenced,
    )
    if (parts.length === 0 && (schemaType.isRequired || pathName === '_id')) {
      required.push(pathName)
    }
  })
  if (required.length > 0) {
    root.required = required
  }
  return root
}

function schemaTypeToOpenAPI(
  schemaType: SchemaType,
  schemaNames: Map<MongooseSchema, string>,
  referenced: string[],
): SchemaObject | ReferenceObject {
  const { instance } = schemaType
  const options = schemaType.options as { enum?: unknown; ref?: unknown }
  switch (instance) {
    case 'String': {
      const { enumValues } = schemaType as SchemaType & {
        enumValues?: string[]
      }
      return enumValues && enumValues.length > 0
        ? { type: 'string', enum: enumValues }
        : { type: 'string' }
    }
    case 'Number': {
      return Array.isArray(options.enum)
        ? { type: 'number', enum: options.enum }
        : { type: 'number' }
    }
    case 'Boolean': {
      return { type: 'boolean' }
    }
    case 'Date': {
      return { type: 'string', format: 'date-time' }
    }
    case 'ObjectId':
    case 'ObjectID': {
      return typeof options.ref === 'string'
        ? { type: 'string', description: `ID of a ${options.ref}` }
        : { type: 'string', description: 'ID' }
    }
    case 'Array': {
      const { embeddedSchemaType, caster } = schemaType as SchemaType & {
        embeddedSchemaType?: SchemaType
        caster?: SchemaType
      }
      const itemType = embeddedSchemaType ?? caster
      return {
        type: 'array',
        items: itemType
          ? schemaTypeToOpenAPI(itemType, schemaNames, referenced)
          : {},
      }
    }
    case 'Map': {
      const valueType = (
        schemaType as SchemaType & { $__schemaType?: SchemaType }
      ).$__schemaType
      return {
        type: 'object',
        additionalProperties: valueType
          ? schemaTypeToOpenAPI(valueType, schemaNames, referenced)
          : true,
      }
    }
    case 'Embedded': {
      const subSchema = (schemaType as SchemaType & { schema: MongooseSchema })
        .schema
      const name = schemaNames.get(subSchema)
      if (name) {
        referenced.push(name)
        return { $ref: `#/components/schemas/${name}` }
      }
      return mongooseToOpenAPI(subSchema, schemaNames, referenced)
    }
    default: {
      return {}
    }
  }
}

/**
 * The body of `POST /changes` is a serialized change, whose properties depend
 * on its type. List the types, and the role each one needs.
 */
function describeChangeBody(document: OpenAPIObject) {
  const schema = document.components?.schemas?.SubmitChangeDto
  if (!schema || '$ref' in schema) {
    throw new Error('Schema for submitting a change not found')
  }
  const typeName = schema.properties?.typeName
  if (!typeName || '$ref' in typeName) {
    throw new Error('Schema for submitting a change has no typeName')
  }
  const typeNames = Object.keys(changes).toSorted()
  typeName.enum = typeNames
  schema.additionalProperties = true

  const operation = document.paths['/changes']?.post
  if (!operation) {
    throw new Error('Operation for submitting a change not found')
  }
  const rows = typeNames.map(
    (name) =>
      `| \`${name}\` | ${roleDescriptions[getRequiredRoleForChange(name)]} |`,
  )
  operation.description = [
    operation.description,
    'Each type of change also requires a role:',
    ['| Change type | Required role |', '| --- | --- |', ...rows].join('\n'),
  ].join('\n\n')
}

await main()
